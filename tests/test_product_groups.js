const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const items=JSON.parse(fs.readFileSync('catalog/menu.json')).items.filter(p=>p.category!=='Extras');
const elements=new Map();
const document={querySelector(selector){if(!elements.has(selector))elements.set(selector,{value:'',innerHTML:'',textContent:''});return elements.get(selector);}};
const context=vm.createContext({document,Intl,fetch:()=>new Promise(()=>{})});
vm.runInContext(fs.readFileSync('static/product-groups.js','utf8'),context);
context.input=items;
const groups=JSON.parse(vm.runInContext('JSON.stringify(groupPresentations(input))',context));
assert.equal(groups.length,123);
assert.equal(groups.flatMap(p=>p.variants).length,items.length);
const americano=groups.find(p=>p.name==='Americano');
assert.deepEqual(americano.variants.map(p=>[p.size,p.price]),[['Chico',3000],['Grande',4000]]);
context.input=[{name:'Café · Chico',category:'A',id:1},{name:'Café · Grande',category:'B',id:2},{name:'Hamburguesa',category:'A',id:3}];
assert.equal(vm.runInContext('groupPresentations(input).length',context),3);
vm.runInContext(fs.readFileSync('static/food-images.js','utf8'),context);
vm.runInContext(fs.readFileSync('static/menu.js','utf8'),context);
context.input=items;
vm.runInContext('items=input;render()',context);
const html=document.querySelector('#sections').innerHTML;
assert.equal((html.match(/<article>/g)||[]).length,123);
assert.ok(html.includes('<h3>Americano</h3>'));
assert.ok(!html.includes('<h3>Americano · Chico</h3>'));
assert.match(html,/Chico \$30.*<br>Grande \$40/);
console.log('123 tarjetas agrupadas: tamaños y precios conservados, categorías separadas y menú renderizado.');
